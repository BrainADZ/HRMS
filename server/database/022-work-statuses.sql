CREATE TABLE work_statuses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id),
  kind TEXT NOT NULL CHECK (kind IN ('travel', 'on_site')),
  start_at TEXT NOT NULL,
  end_at TEXT,
  reason TEXT NOT NULL,
  created_by INTEGER NOT NULL REFERENCES users(id),
  CHECK (end_at IS NULL OR end_at >= start_at)
);
CREATE UNIQUE INDEX idx_work_status_active ON work_statuses(employee_id) WHERE end_at IS NULL;
CREATE INDEX idx_work_status_history ON work_statuses(employee_id, start_at);
ALTER TABLE work_sessions ADD COLUMN work_status_id INTEGER REFERENCES work_statuses(id);
