CREATE TABLE travel_trips (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project TEXT NOT NULL,
  city TEXT NOT NULL,
  site TEXT NOT NULL,
  from_date TEXT NOT NULL,
  to_date TEXT NOT NULL,
  purpose TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected','Submitted','Closed')),
  requested_by INTEGER NOT NULL REFERENCES users(id),
  approver_id INTEGER NOT NULL REFERENCES users(id),
  decision_note TEXT,
  decided_at TEXT,
  final_summary TEXT,
  submitted_at TEXT,
  closed_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  CHECK (to_date >= from_date)
);
CREATE TABLE travel_members (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id INTEGER NOT NULL REFERENCES travel_trips(id) ON DELETE CASCADE,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  UNIQUE (trip_id, employee_id)
);
CREATE TABLE travel_updates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id INTEGER NOT NULL REFERENCES travel_members(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id),
  date TEXT NOT NULL,
  status TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  photo TEXT,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  accuracy DOUBLE PRECISION,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
ALTER TABLE work_sessions ADD COLUMN travel_member_id INTEGER REFERENCES travel_members(id);
ALTER TABLE work_sessions ADD COLUMN activity_type TEXT NOT NULL DEFAULT 'duty' CHECK (activity_type IN ('duty','travel'));
CREATE TABLE travel_reminders (
  member_id INTEGER NOT NULL REFERENCES travel_members(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  PRIMARY KEY (member_id, date)
);
CREATE INDEX idx_travel_approver ON travel_trips(approver_id, status);
CREATE INDEX idx_travel_members_employee ON travel_members(employee_id, trip_id);
CREATE INDEX idx_travel_updates_member ON travel_updates(member_id, created_at);
CREATE INDEX idx_work_travel_member ON work_sessions(travel_member_id);
