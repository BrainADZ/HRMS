-- Additive, opt-in authorization configuration. No existing role, account or
-- permission is reassigned by this migration. Only explicit CEO/admin actions
-- assign the new roles; new role permissions start empty until the CEO sets them.
CREATE TABLE role_assignments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER REFERENCES employees(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK(role IN ('ceo','admin','head','manager','employee')),
  vertical_id INTEGER REFERENCES verticals(id),
  department_id INTEGER REFERENCES departments(id),
  CHECK ((employee_id IS NOT NULL) <> (user_id IS NOT NULL)),
  CHECK (role IN ('head','manager') OR (vertical_id IS NULL AND department_id IS NULL))
);
CREATE UNIQUE INDEX role_assignments_employee_unique ON role_assignments(employee_id,role,COALESCE(vertical_id,0),COALESCE(department_id,0)) WHERE employee_id IS NOT NULL;
CREATE UNIQUE INDEX role_assignments_user_unique ON role_assignments(user_id,role,COALESCE(vertical_id,0),COALESCE(department_id,0)) WHERE user_id IS NOT NULL;
CREATE TABLE role_permission_rules (
  role TEXT NOT NULL CHECK(role IN ('ceo','admin','head','manager','employee')),
  permission TEXT NOT NULL,
  allowed INTEGER NOT NULL CHECK(allowed IN (0,1)),
  PRIMARY KEY(role,permission)
);
CREATE TABLE permission_state (id INTEGER PRIMARY KEY CHECK(id=1), revision INTEGER NOT NULL DEFAULT 0);
