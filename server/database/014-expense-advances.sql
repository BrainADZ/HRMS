CREATE TABLE expense_advances (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  requested_by INTEGER NOT NULL REFERENCES users(id),
  amount INTEGER NOT NULL CHECK (amount > 0),
  purpose TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending Admin' CHECK (status IN ('Pending Admin','Rejected','Awaiting Acceptance','Active','Submitted','Settled')),
  entries TEXT NOT NULL DEFAULT '[]',
  admin_by INTEGER REFERENCES users(id),
  approved_at TEXT,
  accepted_at TEXT,
  submitted_at TEXT,
  settled_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE INDEX expense_advances_employee_idx ON expense_advances(employee_id, created_at DESC);
