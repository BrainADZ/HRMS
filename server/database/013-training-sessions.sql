CREATE TABLE IF NOT EXISTS training_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  agenda TEXT NOT NULL DEFAULT '',
  trainer TEXT NOT NULL,
  starts_at TEXT NOT NULL,
  duration_minutes INTEGER NOT NULL DEFAULT 60,
  mode TEXT NOT NULL DEFAULT 'In person',
  venue TEXT,
  status TEXT NOT NULL DEFAULT 'Scheduled',
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE INDEX IF NOT EXISTS idx_training_sessions_start ON training_sessions(starts_at);

CREATE TABLE IF NOT EXISTS training_session_assignments (
  session_id INTEGER NOT NULL REFERENCES training_sessions(id) ON DELETE CASCADE,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  assigned_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  attended_at TEXT,
  attendance_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  PRIMARY KEY (session_id, employee_id)
);
CREATE INDEX IF NOT EXISTS idx_training_session_employee ON training_session_assignments(employee_id);
