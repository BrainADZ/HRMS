CREATE TABLE IF NOT EXISTS employee_career_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  effective_date TEXT NOT NULL,
  event_type TEXT NOT NULL CHECK (event_type IN ('Joining','Promotion','Increment','Role Change','Salary Adjustment')),
  designation TEXT,
  previous_ctc INTEGER,
  new_ctc INTEGER,
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE INDEX IF NOT EXISTS employee_career_events_employee_date_idx
  ON employee_career_events(employee_id, effective_date, id);
