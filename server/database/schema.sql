
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS verticals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE, short TEXT NOT NULL,
  tagline TEXT, color TEXT NOT NULL DEFAULT '#1A6DF0'
);
CREATE TABLE IF NOT EXISTS departments (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS locations (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE);

CREATE TABLE IF NOT EXISTS employees (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL UNIQUE,
  phone TEXT, gender TEXT, dob TEXT, photo TEXT,
  vertical_id INTEGER REFERENCES verticals(id) DEFERRABLE INITIALLY IMMEDIATE,
  department_id INTEGER REFERENCES departments(id) DEFERRABLE INITIALLY IMMEDIATE,
  designation TEXT, grade TEXT,
  manager_id INTEGER REFERENCES employees(id) DEFERRABLE INITIALLY IMMEDIATE,
  employment_type TEXT NOT NULL DEFAULT 'Full-time',
  location_id INTEGER REFERENCES locations(id) DEFERRABLE INITIALLY IMMEDIATE,
  work_place TEXT CHECK (work_place IN ('wfh', 'onsite')),
  join_date TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Active',
  exit_date TEXT,
  about TEXT,
  skills TEXT NOT NULL DEFAULT '[]',
  certifications TEXT NOT NULL DEFAULT '[]',
  ctc INTEGER NOT NULL DEFAULT 0,
  monthly_tds INTEGER NOT NULL DEFAULT 0,
  pan TEXT, uan TEXT, bank_name TEXT, bank_account TEXT, ifsc TEXT,
  address TEXT, emergency_contact TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE INDEX IF NOT EXISTS idx_emp_manager ON employees(manager_id);
CREATE INDEX IF NOT EXISTS idx_emp_status ON employees(status);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','hr','manager','employee')),
  employee_id INTEGER UNIQUE REFERENCES employees(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  active INTEGER NOT NULL DEFAULT 1,
  must_change_password INTEGER NOT NULL DEFAULT 0,
  last_login TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE IF NOT EXISTS leave_types (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  annual_quota DOUBLE PRECISION,
  accrual TEXT NOT NULL DEFAULT 'annual',
  carry_forward_max DOUBLE PRECISION NOT NULL DEFAULT 0,
  paid INTEGER NOT NULL DEFAULT 1,
  calendar_days INTEGER NOT NULL DEFAULT 0,
  gender TEXT,
  kind TEXT NOT NULL DEFAULT 'leave',
  color TEXT NOT NULL DEFAULT '#1A6DF0',
  icon TEXT NOT NULL DEFAULT 'calendar',
  rule TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  sort INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS leave_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  leave_type_id INTEGER NOT NULL REFERENCES leave_types(id) DEFERRABLE INITIALLY IMMEDIATE,
  from_date TEXT NOT NULL, to_date TEXT NOT NULL,
  half_day INTEGER NOT NULL DEFAULT 0,
  days DOUBLE PRECISION NOT NULL,
  reason TEXT,
  status TEXT NOT NULL DEFAULT 'Pending',
  decided_by INTEGER REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  decided_at TEXT, decision_note TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
CREATE INDEX IF NOT EXISTS idx_leave_emp ON leave_requests(employee_id, from_date);
CREATE INDEX IF NOT EXISTS idx_leave_dates ON leave_requests(from_date, to_date);

CREATE TABLE IF NOT EXISTS holidays (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date TEXT NOT NULL, name TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'Company', UNIQUE(date, name)
);

CREATE TABLE IF NOT EXISTS attendance (
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  date TEXT NOT NULL,
  status TEXT NOT NULL,
  check_in TEXT, check_out TEXT, note TEXT,
  updated_by INTEGER,
  PRIMARY KEY (employee_id, date)
);
CREATE INDEX IF NOT EXISTS idx_att_date ON attendance(date);

-- A day can have several work sessions (check in, step out, check in again).
-- gap_reason/gap_note explain the time away before the session started.
CREATE TABLE IF NOT EXISTS work_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  date TEXT NOT NULL,
  start_at TEXT NOT NULL, end_at TEXT,
  mode TEXT NOT NULL DEFAULT 'office',
  ended_by TEXT,
  gap_reason TEXT, gap_note TEXT
);
CREATE INDEX IF NOT EXISTS idx_ws_emp_date ON work_sessions(employee_id, date);
CREATE UNIQUE INDEX IF NOT EXISTS idx_ws_one_open ON work_sessions(employee_id, date) WHERE end_at IS NULL;

-- Days worked short of the required hours, explained by the employee and
-- approved or rejected by their reporting manager or an administrator.
CREATE TABLE IF NOT EXISTS hour_shortfalls (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  date TEXT NOT NULL,
  worked_minutes INTEGER NOT NULL,
  required_minutes INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'Awaiting explanation',
  reason TEXT, explained_at TEXT,
  decided_by INTEGER REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE, decided_at TEXT, decision_note TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  UNIQUE (employee_id, date)
);
CREATE INDEX IF NOT EXISTS idx_short_status ON hour_shortfalls(status);

-- Offices for the sign-in location check: a point with a radius, and
-- optional network addresses (public IP or LAN ranges, comma separated).
CREATE TABLE IF NOT EXISTS office_sites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  location_id INTEGER REFERENCES locations(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  lat DOUBLE PRECISION NOT NULL, lng DOUBLE PRECISION NOT NULL,
  radius_m INTEGER NOT NULL DEFAULT 300,
  ip_ranges TEXT,
  active INTEGER NOT NULL DEFAULT 1
);

-- Where people were when they signed in, checked in, or while their work
-- clock was running, and sign-ins refused for being outside an office.
CREATE TABLE IF NOT EXISTS location_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  employee_id INTEGER REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  at TEXT NOT NULL,
  event TEXT NOT NULL,
  result TEXT NOT NULL,
  site_id INTEGER REFERENCES office_sites(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
  site_name TEXT,
  distance_m INTEGER, lat DOUBLE PRECISION, lng DOUBLE PRECISION, accuracy_m INTEGER,
  ip TEXT, note TEXT
);
CREATE INDEX IF NOT EXISTS idx_loclog_at ON location_log(at);
CREATE INDEX IF NOT EXISTS idx_loclog_emp ON location_log(employee_id, at);

