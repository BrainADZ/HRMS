// Review aid: enumerate literal client API references and registered routes.
// Runtime-composed paths and authorization still require integration tests.
import fs from 'node:fs/promises';
import path from 'node:path';

async function files(directory) {
  const result = [];
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) result.push(...(await files(file)));
    else if (/\.(jsx?|tsx?)$/.test(file)) result.push(file);
  }
  return result;
}
const lines = [
  '# API and UI reference inventory',
  '',
  'Generated by `node server/scripts/audit-api-map.js`. This is a source inventory, not proof that every interaction works. Template parameters, composed paths and middleware permissions need the automated/API/browser checks.',
  '',
  '## Backend routes',
  '',
  '| Source | Method | Path |',
  '|---|---|---|',
];
let routeCount = 0,
  referenceCount = 0;
for (const file of await files('server/routes')) {
  const source = await fs.readFile(file, 'utf8');
  for (const match of source.matchAll(/r\.(get|post|put|patch|delete)\(['"`]([^'"`]+)['"`]/g)) {
    lines.push(`| ${file.replaceAll('\\', '/')} | ${match[1].toUpperCase()} | \`${match[2]}\` |`);
    routeCount++;
  }
}
lines.push(
  '',
  '## Frontend references',
  '',
  '| Source | Call | Path expression |',
  '|---|---|---|',
);
for (const file of await files('client/src')) {
  const source = await fs.readFile(file, 'utf8');
  const seen = new Set();
  for (const match of source.matchAll(
    /\b(api(?:\.(?:get|post|put|del|upload))?|useApi|download|postDownload)\(\s*(['"`])([^'"`\n]+)\2/g,
  )) {
    const key = match[1] + match[3];
    if (seen.has(key)) continue;
    seen.add(key);
    lines.push(
      `| ${file.replaceAll('\\', '/')} | ${match[1]} | \`${match[3].replaceAll('|', '&#124;')}\` |`,
    );
    referenceCount++;
  }
}
lines.push(
  '',
  `${routeCount} backend registrations and ${referenceCount} distinct literal client references. Variable-only calls and download arrays require separate source review.`,
  '',
);
await fs.writeFile('API_UI_MAP.md', lines.join('\n'));
console.log(`API_UI_MAP.md: ${routeCount} routes, ${referenceCount} client references`);
